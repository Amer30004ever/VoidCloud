#!/usr/bin/env node
/**
 * Derives the canonical list of physical table names from schema.prisma so the
 * restore drill can verify SCHEMA COMPLETENESS, not just "some tables exist".
 *
 * Output: database/scripts/expected-tables.txt (one table name per line, sorted)
 * Also regenerates kubernetes/postgres/expected-tables-configmap.yaml.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '../..');
const schema = readFileSync(resolve(repo, 'database/prisma/schema.prisma'), 'utf8');

const lines = schema.split(/\r?\n/);
const tables = new Set();
const listRelationCounts = new Map();

let current = null;
let body = [];
for (const line of lines) {
  const start = line.match(/^model\s+(\w+)\s*\{/);
  if (start) {
    current = start[1];
    body = [];
    continue;
  }
  if (current && /^\}/.test(line)) {
    const map = body.map((l) => l.match(/@@map\("([^"]+)"\)/)).find(Boolean);
    tables.add(map ? map[1] : current);
    current = null;
    continue;
  }
  if (current) {
    body.push(line);
    // A named relation on a list field is only an IMPLICIT many-to-many join
    // table when BOTH sides are lists. A named one-to-many (list on one side,
    // scalar + fields/references on the other) has no join table at all.
    const rel = line.match(/\w+\s+\w+\[\]\s+@relation\("([^"]+)"\)/);
    if (rel) listRelationCounts.set(rel[1], (listRelationCounts.get(rel[1]) ?? 0) + 1);
    // Unnamed implicit m2m: `field Other[]` with no @relation attribute on
    // either side produces the join table `_AToB` (model names, sorted).
    const plain = line.match(/^\s*\w+\s+(\w+)\[\]\s*$/);
    if (plain) plainLists.push([current, plain[1]]);
  }
}
for (const [name, count] of listRelationCounts) {
  if (count >= 2) tables.add(`_${name}`);
}
for (const [a, b] of plainLists) {
  if (plainLists.some(([x, y]) => x === b && y === a)) {
    tables.add(`_${[a, b].sort().join('To')}`);
  }
}



const sorted = [...tables].sort();
writeFileSync(resolve(repo, 'database/scripts/expected-tables.txt'), sorted.join('\n') + '\n');

const cm = `# GENERATED by database/scripts/generate-expected-tables.mjs — do not edit by hand.
apiVersion: v1
kind: ConfigMap
metadata:
  name: voidcloud-expected-tables
  namespace: voidcloud
data:
  expected-tables.txt: |
${sorted.map((t) => `    ${t}`).join('\n')}
`;
writeFileSync(resolve(repo, 'kubernetes/postgres/expected-tables-configmap.yaml'), cm);

console.log(`Wrote ${sorted.length} expected tables.`);
