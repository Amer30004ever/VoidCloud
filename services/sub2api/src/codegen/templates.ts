/**
 * Generate a complete, runnable React + Vite + Supabase CRUD app for the inferred schema.
 * Returns a path -> file-contents map.
 */
export function generateProjectFiles(options: GenerateOptions): Record<string, string> {
  const { projectName, description, schema, supabaseUrl, supabaseAnonKey } = options;
  const name = slug(projectName);
  const files: Record<string, string> = {};

  files['package.json'] = `${JSON.stringify(
    {
      name,
      private: true,
      version: '0.1.0',
      type: 'module',
      scripts: {
        dev: 'vite',
        build: 'tsc -b && vite build',
        preview: 'vite preview',
      },
      dependencies: {
        '@supabase/supabase-js': '^2.45.0',
        react: '^18.3.1',
        'react-dom': '^18.3.1',
        'react-router-dom': '^6.26.0',
      },
      devDependencies: {
        '@types/react': '^18.3.3',
        '@types/react-dom': '^18.3.0',
        '@vitejs/plugin-react': '^4.3.1',
        typescript: '^5.5.4',
        vite: '^5.4.0',
      },
    },
    null,
    2,
  )}\n`;

  files['vite.config.ts'] = `import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';

export default defineConfig({
  plugins: [react()],
  server: { port: 5173 },
});
`;

  files['tsconfig.json'] = `${JSON.stringify(
    {
      compilerOptions: {
        target: 'ES2020',
        lib: ['ES2020', 'DOM', 'DOM.Iterable'],
        module: 'ESNext',
        moduleResolution: 'bundler',
        jsx: 'react-jsx',
        strict: true,
        skipLibCheck: true,
        noEmit: true,
        isolatedModules: true,
        resolveJsonModule: true,
      },
      include: ['src'],
    },
    null,
    2,
  )}\n`;

  files['index.html'] = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>${projectName}</title>
  </head>
  <body>
    <div id="root"></div>
    <script type="module" src="/src/main.tsx"></script>
  </body>
</html>
`;

  files['.gitignore'] = 'node_modules\ndist\n.env\n.env.local\n';

  files['.env.example'] = `VITE_SUPABASE_URL=${supabaseUrl || 'https://YOUR-PROJECT.supabase.co'}
VITE_SUPABASE_ANON_KEY=${supabaseAnonKey || 'YOUR-ANON-KEY'}
`;

  files['src/main.tsx'] = `import React from 'react';
import ReactDOM from 'react-dom/client';
import App from './App';
import './index.css';

ReactDOM.createRoot(document.getElementById('root')!).render(
  <React.StrictMode>
    <App />
  </React.StrictMode>,
);
`;

  files['src/index.css'] = STYLES;
  files['src/App.tsx'] = appFile(schema, projectName);

  files['src/lib/supabase.ts'] = `import { createClient } from '@supabase/supabase-js';

const url = import.meta.env.VITE_SUPABASE_URL;
const anonKey = import.meta.env.VITE_SUPABASE_ANON_KEY;

if (!url || !anonKey) {
  throw new Error('Missing VITE_SUPABASE_URL or VITE_SUPABASE_ANON_KEY. Copy .env.example to .env.');
}

export const supabase = createClient(url, anonKey);
`;

  files['src/vite-env.d.ts'] = `/// <reference types="vite/client" />

interface ImportMetaEnv {
  readonly VITE_SUPABASE_URL: string;
  readonly VITE_SUPABASE_ANON_KEY: string;
}

interface ImportMeta {
  readonly env: ImportMetaEnv;
}
`;

  files['src/types.ts'] = `${schema.entities.map(tsInterface).join('\n\n')}\n`;

  if (schema.auth) {
    files['src/components/AuthGate.tsx'] = AUTH_GATE;
  }

  for (const entity of schema.entities) {
    files[`src/hooks/use${entity.pascalPlural}.ts`] = hookFile(entity);
    files[`src/components/${entity.pascal}Form.tsx`] = formFile(entity);
    files[`src/pages/${entity.pascal}ListPage.tsx`] = listFile(entity);
    files[`src/pages/${entity.pascal}DetailPage.tsx`] = detailFile(entity);
  }

  files['supabase/migrations/0001_init.sql'] = migration(schema);

  files['README.md'] = `# ${projectName}

${description || 'Generated by sub2api Studio.'}

## Stack

- React 18 + Vite + TypeScript
- React Router
- Supabase (Postgres, Auth, Row Level Security)

## Entities

${schema.entities.map((e) => `- **${e.pascalPlural}** (\`${e.table}\`): ${e.fields.map((f) => f.name).join(', ')}`).join('\n')}

## Setup

1. Install dependencies:

   \`\`\`bash
   npm install
   \`\`\`

2. Copy the environment file and fill in your Supabase credentials:

   \`\`\`bash
   cp .env.example .env
   \`\`\`

3. Apply the database schema. Either paste \`supabase/migrations/0001_init.sql\`
   into the Supabase SQL editor, or run:

   \`\`\`bash
   supabase db push
   \`\`\`

4. Start the dev server:

   \`\`\`bash
   npm run dev
   \`\`\`

   The app runs at http://localhost:5173

## Security

Every table has Row Level Security enabled with owner-scoped policies
(\`auth.uid() = user_id\`), plus explicit grants for \`authenticated\` and
\`service_role\`. Rows are only visible to the user that created them.
`;

  return files;
}
