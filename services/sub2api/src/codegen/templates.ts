import { InferredEntity, InferredSchema } from './schema-inference';

export interface GenerateOptions {
  projectName: string;
  description: string;
  schema: InferredSchema;
  supabaseUrl?: string | null;
  supabaseAnonKey?: string | null;
}

function slug(name: string): string {
  return (
    name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '') || 'generated-app'
  );
}

function tsInterface(entity: InferredEntity): string {
  const lines = entity.fields.map((f) => `  ${f.name}${f.required ? '' : '?'}: ${f.tsType} | null;`);
  return [
    `export interface ${entity.pascal} {`,
    '  id: string;',
    '  created_at: string;',
    ...lines,
    '}',
  ].join('\n');
}

function emptyRecord(entity: InferredEntity): string {
  const parts = entity.fields.map((f) => {
    if (f.tsType === 'boolean') return `${f.name}: false`;
    if (f.tsType === 'number') return `${f.name}: 0`;
    return `${f.name}: ''`;
  });
  return `{ ${parts.join(', ')} }`;
}

function migration(schema: InferredSchema): string {
  const blocks = schema.entities.map((e) => {
    const cols = e.fields
      .map((f) => `  ${f.name} ${f.sqlType}${f.required ? ' not null' : ''}`)
      .join(',\n');
    return `-- ${e.label}
create table if not exists public.${e.table} (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
${cols},
  created_at timestamptz not null default now()
);

grant select, insert, update, delete on public.${e.table} to authenticated;
grant all on public.${e.table} to service_role;

alter table public.${e.table} enable row level security;

create policy "${e.table}_select_own" on public.${e.table}
  for select to authenticated using (auth.uid() = user_id);
create policy "${e.table}_insert_own" on public.${e.table}
  for insert to authenticated with check (auth.uid() = user_id);
create policy "${e.table}_update_own" on public.${e.table}
  for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "${e.table}_delete_own" on public.${e.table}
  for delete to authenticated using (auth.uid() = user_id);`;
  });

  return `-- Generated by sub2api Studio
-- Row Level Security is enabled on every table by default.

${blocks.join('\n\n')}
`;
}

function hookFile(entity: InferredEntity): string {
  return `import { useCallback, useEffect, useState } from 'react';
import { supabase } from '../lib/supabase';
import type { ${entity.pascal} } from '../types';

export function use${entity.pascalPlural}() {
  const [items, setItems] = useState<${entity.pascal}[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  const refresh = useCallback(async () => {
    setLoading(true);
    const { data, error } = await supabase
      .from('${entity.table}')
      .select('*')
      .order('created_at', { ascending: false });
    if (error) setError(error.message);
    else {
      setItems(data as ${entity.pascal}[]);
      setError(null);
    }
    setLoading(false);
  }, []);

  useEffect(() => {
    void refresh();
  }, [refresh]);

  const create = useCallback(
    async (values: Partial<${entity.pascal}>) => {
      const { error } = await supabase.from('${entity.table}').insert(values);
      if (error) throw new Error(error.message);
      await refresh();
    },
    [refresh],
  );

  const update = useCallback(
    async (id: string, values: Partial<${entity.pascal}>) => {
      const { error } = await supabase.from('${entity.table}').update(values).eq('id', id);
      if (error) throw new Error(error.message);
      await refresh();
    },
    [refresh],
  );

  const remove = useCallback(
    async (id: string) => {
      const { error } = await supabase.from('${entity.table}').delete().eq('id', id);
      if (error) throw new Error(error.message);
      await refresh();
    },
    [refresh],
  );

  return { items, loading, error, refresh, create, update, remove };
}
`;
}

function formFile(entity: InferredEntity): string {
  const inputs = entity.fields
    .map((f) => {
      const label = f.name.replace(/_/g, ' ');
      if (f.inputType === 'textarea') {
        return `      <label className="field">
        <span>${label}</span>
        <textarea
          value={String(values.${f.name} ?? '')}
          onChange={(e) => set('${f.name}', e.target.value)}
          rows={4}
        />
      </label>`;
      }
      if (f.inputType === 'checkbox') {
        return `      <label className="field field-inline">
        <input
          type="checkbox"
          checked={Boolean(values.${f.name})}
          onChange={(e) => set('${f.name}', e.target.checked)}
        />
        <span>${label}</span>
      </label>`;
      }
      const cast = f.tsType === 'number' ? 'Number(e.target.value)' : 'e.target.value';
      return `      <label className="field">
        <span>${label}</span>
        <input
          type="${f.inputType}"
          value={String(values.${f.name} ?? '')}
          onChange={(e) => set('${f.name}', ${cast})}
          ${f.required ? 'required' : ''}
        />
      </label>`;
    })
    .join('\n');

  return `import { FormEvent, useState } from 'react';
import type { ${entity.pascal} } from '../types';

interface Props {
  initial?: Partial<${entity.pascal}>;
  submitLabel?: string;
  onSubmit: (values: Partial<${entity.pascal}>) => Promise<void> | void;
  onCancel?: () => void;
}

export function ${entity.pascal}Form({ initial, submitLabel = 'Save', onSubmit, onCancel }: Props) {
  const [values, setValues] = useState<Partial<${entity.pascal}>>(initial ?? ${emptyRecord(entity)});
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const set = (key: string, value: unknown) =>
    setValues((prev) => ({ ...prev, [key]: value as never }));

  const handleSubmit = async (e: FormEvent) => {
    e.preventDefault();
    setBusy(true);
    setError(null);
    try {
      await onSubmit(values);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Something went wrong');
    } finally {
      setBusy(false);
    }
  };

  return (
    <form className="card form" onSubmit={handleSubmit}>
${inputs}
      {error ? <p className="error">{error}</p> : null}
      <div className="row">
        <button type="submit" disabled={busy}>
          {busy ? 'Saving...' : submitLabel}
        </button>
        {onCancel ? (
          <button type="button" className="ghost" onClick={onCancel}>
            Cancel
          </button>
        ) : null}
      </div>
    </form>
  );
}
`;
}

function listFile(entity: InferredEntity): string {
  const primary = entity.fields[0]?.name ?? 'id';
  const secondary = entity.fields[1]?.name;
  return `import { useState } from 'react';
import { Link } from 'react-router-dom';
import { use${entity.pascalPlural} } from '../hooks/use${entity.pascalPlural}';
import { ${entity.pascal}Form } from '../components/${entity.pascal}Form';

export function ${entity.pascal}ListPage() {
  const { items, loading, error, create, remove } = use${entity.pascalPlural}();
  const [creating, setCreating] = useState(false);

  return (
    <section>
      <header className="page-header">
        <h1>${entity.pascalPlural}</h1>
        <button onClick={() => setCreating((v) => !v)}>
          {creating ? 'Close' : 'New ${entity.label}'}
        </button>
      </header>

      {creating ? (
        <${entity.pascal}Form
          submitLabel="Create ${entity.label}"
          onSubmit={async (values) => {
            await create(values);
            setCreating(false);
          }}
          onCancel={() => setCreating(false)}
        />
      ) : null}

      {loading ? <p className="muted">Loading...</p> : null}
      {error ? <p className="error">{error}</p> : null}
      {!loading && items.length === 0 ? <p className="muted">No ${entity.table} yet.</p> : null}

      <ul className="list">
        {items.map((item) => (
          <li key={item.id} className="card row-between">
            <div>
              <Link to={\`/${entity.table}/\${item.id}\`}>{String(item.${primary} ?? 'Untitled')}</Link>
              ${secondary ? `<p className="muted">{String(item.${secondary} ?? '')}</p>` : ''}
            </div>
            <button className="ghost" onClick={() => void remove(item.id)}>
              Delete
            </button>
          </li>
        ))}
      </ul>
    </section>
  );
}
`;
}

function detailFile(entity: InferredEntity): string {
  const primary = entity.fields[0]?.name ?? 'id';
  return `import { useNavigate, useParams, Link } from 'react-router-dom';
import { use${entity.pascalPlural} } from '../hooks/use${entity.pascalPlural}';
import { ${entity.pascal}Form } from '../components/${entity.pascal}Form';

export function ${entity.pascal}DetailPage() {
  const { id } = useParams<{ id: string }>();
  const navigate = useNavigate();
  const { items, loading, update, remove } = use${entity.pascalPlural}();
  const item = items.find((entry) => entry.id === id);

  if (loading) return <p className="muted">Loading...</p>;
  if (!item) return <p className="muted">${entity.label} not found. <Link to="/${entity.table}">Back</Link></p>;

  return (
    <section>
      <header className="page-header">
        <h1>{String(item.${primary} ?? '${entity.label}')}</h1>
        <button
          className="ghost"
          onClick={async () => {
            await remove(item.id);
            navigate('/${entity.table}');
          }}
        >
          Delete
        </button>
      </header>

      <${entity.pascal}Form
        initial={item}
        submitLabel="Save changes"
        onSubmit={(values) => update(item.id, values)}
        onCancel={() => navigate('/${entity.table}')}
      />
    </section>
  );
}
`;
}

function appFile(schema: InferredSchema, projectName: string): string {
  const imports = schema.entities
    .map(
      (e) =>
        `import { ${e.pascal}ListPage } from './pages/${e.pascal}ListPage';\nimport { ${e.pascal}DetailPage } from './pages/${e.pascal}DetailPage';`,
    )
    .join('\n');

  const routes = schema.entities
    .map(
      (e) =>
        `        <Route path="/${e.table}" element={<${e.pascal}ListPage />} />\n        <Route path="/${e.table}/:id" element={<${e.pascal}DetailPage />} />`,
    )
    .join('\n');

  const navLinks = schema.entities
    .map((e) => `          <NavLink to="/${e.table}">${e.pascalPlural}</NavLink>`)
    .join('\n');

  const home = schema.entities[0];

  return `import { BrowserRouter, NavLink, Navigate, Route, Routes } from 'react-router-dom';
${schema.auth ? "import { AuthGate } from './components/AuthGate';\n" : ''}${imports}

export default function App() {
  const content = (
    <div className="app">
      <nav className="nav">
        <strong>${projectName}</strong>
        <div className="nav-links">
${navLinks}
        </div>
      </nav>
      <main className="main">
        <Routes>
          <Route path="/" element={<Navigate to="/${home.table}" replace />} />
${routes}
          <Route path="*" element={<p className="muted">Page not found.</p>} />
        </Routes>
      </main>
    </div>
  );

  return <BrowserRouter>${schema.auth ? '<AuthGate>{content}</AuthGate>' : '{content}'}</BrowserRouter>;
}
`;
}

const AUTH_GATE = `import { FormEvent, ReactNode, useEffect, useState } from 'react';
import type { Session } from '@supabase/supabase-js';
import { supabase } from '../lib/supabase';

export function AuthGate({ children }: { children: ReactNode }) {
  const [session, setSession] = useState<Session | null>(null);
  const [ready, setReady] = useState(false);
  const [email, setEmail] = useState('');
  const [password, setPassword] = useState('');
  const [mode, setMode] = useState<'signin' | 'signup'>('signin');
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    supabase.auth.getSession().then(({ data }) => {
      setSession(data.session);
      setReady(true);
    });
    const { data: sub } = supabase.auth.onAuthStateChange((_event, next) => setSession(next));
    return () => sub.subscription.unsubscribe();
  }, []);

  if (!ready) return <p className="muted">Loading...</p>;

  if (!session) {
    const submit = async (e: FormEvent) => {
      e.preventDefault();
      setError(null);
      const fn = mode === 'signin' ? supabase.auth.signInWithPassword : supabase.auth.signUp;
      const { error } = await fn({ email, password });
      if (error) setError(error.message);
    };

    return (
      <div className="auth">
        <form className="card form" onSubmit={submit}>
          <h1>{mode === 'signin' ? 'Sign in' : 'Create account'}</h1>
          <label className="field">
            <span>email</span>
            <input type="email" value={email} onChange={(e) => setEmail(e.target.value)} required />
          </label>
          <label className="field">
            <span>password</span>
            <input type="password" value={password} onChange={(e) => setPassword(e.target.value)} required />
          </label>
          {error ? <p className="error">{error}</p> : null}
          <button type="submit">{mode === 'signin' ? 'Sign in' : 'Sign up'}</button>
          <button type="button" className="ghost" onClick={() => setMode(mode === 'signin' ? 'signup' : 'signin')}>
            {mode === 'signin' ? 'Need an account?' : 'Already registered?'}
          </button>
        </form>
      </div>
    );
  }

  return (
    <>
      <div className="session-bar">
        <span className="muted">{session.user.email}</span>
        <button className="ghost" onClick={() => void supabase.auth.signOut()}>
          Sign out
        </button>
      </div>
      {children}
    </>
  );
}
`;

