"use client";

import { useCallback, useEffect, useState } from "react";
import { RefreshCw, Sparkles } from "lucide-react";
import api from "@/lib/api";

interface AdviceResponse {
  advice: string;
  source: "llm" | "heuristic";
}

export default function AiUsageAdvisor() {
  const [data, setData] = useState<AdviceResponse | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(false);

  const load = useCallback(async () => {
    setLoading(true);
    setError(false);
    try {
      const r = await api.get<AdviceResponse>("/notification/ai/usage-advice");
      setData(r.data);
    } catch {
      setError(true);
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    void load();
  }, [load]);

  if (loading) {
    return (
      <div className="rounded-2xl border border-cyan-400/20 bg-cyan-400/5 p-4">
        <div className="h-3 w-28 animate-pulse rounded bg-white/10" />
        <div className="mt-3 h-3 w-full animate-pulse rounded bg-white/10" />
        <div className="mt-2 h-3 w-2/3 animate-pulse rounded bg-white/10" />
      </div>
    );
  }

  if (error || !data) {
    return (
      <div className="rounded-2xl border border-white/10 bg-white/5 p-4">
        <div className="flex items-center justify-between">
          <div className="text-xs font-semibold text-white/70">Usage Advisor</div>
          <button
            type="button"
            onClick={() => void load()}
            className="inline-flex items-center gap-1 rounded-lg border border-white/10 px-2 py-1 text-[11px] text-white/70 hover:bg-white/10"
          >
            <RefreshCw className="h-3 w-3" aria-hidden /> Retry
          </button>
        </div>
        <p className="mt-1 text-sm text-white/50">Advice is unavailable right now.</p>
      </div>
    );
  }

  const isLlm = data.source === "llm";

  return (
    <div className="rounded-2xl border border-cyan-400/20 bg-cyan-400/5 p-4">
      <div className="flex items-center justify-between gap-2">
        <div className="flex items-center gap-1.5 text-xs font-semibold text-cyan-300">
          <Sparkles className="h-3.5 w-3.5" aria-hidden />
          {isLlm ? "AI Usage Advisor" : "Usage Advisor"}
        </div>
        <button
          type="button"
          onClick={() => void load()}
          aria-label="Refresh advice"
          className="rounded-lg border border-white/10 p-1 text-white/60 hover:bg-white/10"
        >
          <RefreshCw className="h-3 w-3" aria-hidden />
        </button>
      </div>
      <p className="mt-1 whitespace-pre-line text-sm text-white/70">{data.advice}</p>
      <p className="mt-1 text-[10px] text-white/30">
        {isLlm
          ? "Generated by the VoidCloud model from your account data — advisory only, no action taken automatically."
          : "Rule-based summary of your account data (AI model unavailable) — advisory only."}
      </p>
    </div>
  );
}
