"use client";

import { useState } from "react";

type ReportRow = {
  id: string;
  date: string;
  vps: string;
  plan: string;
  billing: number;
};

const SAMPLE_DATA: ReportRow[] = [
  { id: "1", date: "2026-07-23", vps: "prod-api", plan: "Pro", billing: 49.99 },
  { id: "2", date: "2026-07-22", vps: "staging-web", plan: "Business", billing: 99.99 },
  { id: "3", date: "2026-07-21", vps: "analytics-worker", plan: "Pro", billing: 49.99 },
  { id: "4", date: "2026-07-20", vps: "monitoring", plan: "Enterprise", billing: 199.99 },
  { id: "5", date: "2026-07-19", vps: "prod-db", plan: "Business", billing: 99.99 },
];

function downloadCsv(rows: ReportRow[]) {
  const header = "ID,Date,VPS,Plan,Billing (USD)";
  const body = rows
    .map((r) => `${r.id},${r.date},${r.vps},${r.plan},${r.billing.toFixed(2)}`)
    .join("\n");
  const csv = `${header}\n${body}`;
  const blob = new Blob([csv], { type: "text/csv;charset=utf-8;" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `voidcloud-report-${Date.now()}.csv`;
  a.click();
  URL.revokeObjectURL(url);
}

function openPdf(rows: ReportRow[]) {
  const total = rows.reduce((s, r) => s + r.billing, 0);
  const rowsHtml = rows
    .map(
      (r) =>
        `<tr><td>${r.id}</td><td>${r.date}</td><td>${r.vps}</td><td>${r.plan}</td><td style="text-align:right">$${r.billing.toFixed(2)}</td></tr>`
    )
    .join("");

  const html = `<!DOCTYPE html>
<html>
<head>
  <title>VoidCloud Report</title>
  <style>
    body { font-family: ui-sans-serif, system-ui, sans-serif; color: #0f172a; padding: 24px; }
    .header { display: flex; align-items: center; justify-content: space-between; }
    .logo { font-weight: 800; font-size: 20px; background: linear-gradient(to right, #22d3ee, #a78bfa); -webkit-background-clip: text; color: transparent; }
    .meta { font-size: 12px; color: #64748b; }
    table { width: 100%; border-collapse: collapse; margin-top: 16px; font-size: 13px; }
    th, td { text-align: left; padding: 8px 12px; border-bottom: 1px solid #e2e8f0; }
    th { color: #64748b; font-weight: 600; text-transform: uppercase; font-size: 11px; letter-spacing: 0.05em; }
    td { color: #1e293b; }
    .total { font-weight: 700; color: #0f172a; }
    .footer { margin-top: 24px; font-size: 11px; color: #94a3b8; }
    @media print { body { padding: 0; } }
  </style>
</head>
<body>
  <div class="header">
    <div>
      <div class="logo">VoidCloud</div>
      <div style="font-weight:600;color:#0f172a;margin-top:2px;">Usage & Billing Report</div>
    </div>
    <div class="meta">${new Date().toLocaleDateString()}</div>
  </div>
  <table>
    <thead><tr><th>ID</th><th>Date</th><th>VPS</th><th>Plan</th><th style="text-align:right">Billing (USD)</th></tr></thead>
    <tbody>${rowsHtml}</tbody>
    <tfoot><tr><td colspan="4" style="text-align:right" class="total">Total</td><td style="text-align:right" class="total">$${total.toFixed(2)}</td></tr></tfoot>
  </table>
  <div class="footer">Generated by VoidCloud · ${new Date().toISOString()}</div>
  <script>window.print();</script>
</body>
</html>`;

  const win = window.open("", "_blank", "width=800,height=1000");
  if (!win) return;
  win.document.write(html);
  win.document.close();
}

export default function ReportsPage() {
  const [rows] = useState<ReportRow[]>(SAMPLE_DATA);

  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div>
          <h1 className="vc-h1">Reports</h1>
          <p className="text-sm text-white/60">Generate and export billing and VPS usage reports.</p>
        </div>
        <div className="flex gap-2">
          <button
            onClick={() => downloadCsv(rows)}
            className="vc-btn vc-btn-secondary hover:bg-white/10"
          >
            Export CSV
          </button>
          <button
            onClick={() => openPdf(rows)}
            className="vc-btn vc-btn-primary"
          >
            Export PDF
          </button>
        </div>
      </div>

      <div className="vc-card">
        <table className="w-full text-sm">
          <thead className="border-b border-white/5 text-left text-xs uppercase text-white/40">
            <tr>
              <th className="p-4">ID</th>
              <th>Date</th>
              <th>VPS</th>
              <th>Plan</th>
              <th className="text-right">Billing</th>
            </tr>
          </thead>
          <tbody>
            {rows.map((r) => (
              <tr key={r.id} className="border-b border-white/5 hover:bg-white/5">
                <td className="p-4 font-medium">{r.id}</td>
                <td className="p-4">{r.date}</td>
                <td className="p-4">{r.vps}</td>
                <td className="p-4">{r.plan}</td>
                <td className="p-4 text-right">${r.billing.toFixed(2)}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </div>
  );
}
